#!/usr/bin/env node
/**
 * Writes android/local.properties pointing at the Android SDK.
 *
 * `expo prebuild --clean` deletes the whole android/ directory, and
 * local.properties is a local, gitignored file that prebuild does not
 * regenerate. Gradle then fails with "SDK location not found" on the next
 * build. With ANDROID_HOME unset on this machine, that happens after every
 * prebuild, so this runs as part of the prebuild and build scripts.
 *
 * Setting ANDROID_HOME permanently makes this unnecessary; it stays as a
 * fallback so a fresh clone builds without environment setup.
 */
const fs = require('fs');
const path = require('path');
const os = require('os');

const PROJECT_ROOT = path.join(__dirname, '..');
const ANDROID_DIR = path.join(PROJECT_ROOT, 'android');
const LOCAL_PROPERTIES = path.join(ANDROID_DIR, 'local.properties');

function findSdk() {
  const candidates = [
    process.env.ANDROID_HOME,
    process.env.ANDROID_SDK_ROOT,
    path.join(os.homedir(), 'AppData', 'Local', 'Android', 'Sdk'),
    path.join(os.homedir(), 'Library', 'Android', 'sdk'),
    path.join(os.homedir(), 'Android', 'Sdk'),
    path.join('C:', 'Android', 'Sdk'),
  ].filter(Boolean);

  for (const candidate of candidates) {
    // platform-tools is the marker that this is a real SDK, not an empty dir.
    if (fs.existsSync(path.join(candidate, 'platform-tools'))) return candidate;
  }
  return null;
}

function main() {
  if (!fs.existsSync(ANDROID_DIR)) {
    // No native project yet — nothing to configure.
    return;
  }

  const sdk = findSdk();
  if (!sdk) {
    console.warn(
      '[ensure-android-sdk] Could not find an Android SDK. Set ANDROID_HOME to your SDK ' +
        'directory (the one containing platform-tools) and re-run.'
    );
    return;
  }

  // Forward slashes are valid in a Java properties file on Windows and avoid
  // the backslash-escaping rules entirely.
  const sdkPath = sdk.replace(/\\/g, '/');
  const contents = `# Generated by scripts/ensure-android-sdk.js — do not edit.\nsdk.dir=${sdkPath}\n`;

  const existing = fs.existsSync(LOCAL_PROPERTIES)
    ? fs.readFileSync(LOCAL_PROPERTIES, 'utf8')
    : null;

  if (existing === contents) return;

  fs.writeFileSync(LOCAL_PROPERTIES, contents, 'utf8');
  console.log(`[ensure-android-sdk] sdk.dir=${sdkPath}`);
}

main();
